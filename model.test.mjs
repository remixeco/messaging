import assert from 'node:assert/strict';
import { initialState, characterCount, publish, feedFor, restoreState, DOMAINS, visiblePosts, toggleMark, normalizeDomain, followDomain } from './model.mjs';
const state = initialState(10000000);
assert.equal(characterCount('👩🏽‍💻e\u0301'), 2);
assert.equal(state.posts['cafe.example'].length, 10);
const old = state.posts['cafe.example'].at(-1);
const other = JSON.stringify(state.posts['studio.example']);
const result = publish(state, 'cafe.example', '🙂'.repeat(150), 11000000);
assert.equal(result.removed.id, old.id);
assert.equal(state.posts['cafe.example'].length, 10);
assert.equal(JSON.stringify(state.posts['studio.example']), other);
assert.equal(feedFor(state)[0].id, result.message.id);
assert.throws(() => publish(state, 'cafe.example', 'x'.repeat(151)));
assert.throws(() => publish(state, 'cafe.example', 'e' + '\u0301'.repeat(4000)));
assert.throws(() => publish(state, 'cafe.example', '   '));
assert.throws(() => publish(state, '__proto__', 'test'));
assert.equal(state.posts['cafe.example'].length, 10);
state.following = [];
assert.equal(feedFor(state).length, 0);
state.following = ['studio.example'];
assert.ok(feedFor(state).every(post => post.domain === 'studio.example'));
assert.deepEqual(restoreState(JSON.stringify(state)), state);
assert.equal(restoreState('{invalid'), null);
assert.equal(restoreState('{}'), null);
assert.equal(restoreState(JSON.stringify({ ...state, following: ['unknown.example'] })), null);
const invalid = structuredClone(state); invalid.posts['studio.example'].push(...invalid.posts['cafe.example']);
assert.equal(restoreState(JSON.stringify(invalid)), null);
for (const domain of DOMAINS) assert.ok(characterCount(domain.example) <= 150);
for (let i = 0; i < 100; i++) publish(state, 'studio.example', `Essai ${i}`, 12000000 + i);
assert.equal(state.posts['studio.example'].length, 10);
assert.equal(state.posts['studio.example'][0].text, 'Essai 99');
const markup = '<img src=x onerror=alert(1)>';
publish(state, 'studio.example', markup);
assert.equal(state.posts['studio.example'][0].text, markup);
console.log('OK : limites Unicode, rotation, domaines isolés, suivi, restauration et entrées invalides.');
const social = initialState(20000000);
assert.equal(visiblePosts(social, 'explore').length, 16);
assert.equal(visiblePosts(social, 'home').length, 13);
assert.equal(visiblePosts(social, 'profile', 'collectif.example').length, 3);
assert.equal(visiblePosts(social, 'profile', 'unknown.example').length, 0);
assert.ok(visiblePosts(social, 'explore', 'cafe.example', 'gateau')[0].text.includes('gâteau'));
assert.equal(visiblePosts(social, 'explore', 'cafe.example', 'introuvable').length, 0);
assert.equal(toggleMark(social, 'likes', 1), true);
assert.equal(toggleMark(social, 'likes', 1), false);
assert.equal(toggleMark(social, 'unknown', 1), false);
assert.equal(toggleMark(social, 'saved', 9999), false);
toggleMark(social, 'saved', 10);
assert.equal(visiblePosts(social, 'saved').length, 1);
assert.equal(visiblePosts(social, 'saved')[0].id, 10);
assert.deepEqual(restoreState(JSON.stringify(social)), social);
publish(social, 'cafe.example', 'Une nouvelle annonce');
assert.equal(visiblePosts(social, 'saved').length, 0);
const legacy = initialState(); delete legacy.likes; delete legacy.saved;
const migrated = restoreState(JSON.stringify(legacy));
assert.deepEqual(migrated.likes, []); assert.deepEqual(migrated.saved, []);
assert.deepEqual(migrated.posts, legacy.posts);
assert.equal(restoreState(JSON.stringify({ ...social, likes: 'incorrect' })), null);
console.log('OK : profils, exploration, recherche, réactions, enregistrements et reprise des anciens essais.');
const subscriptions = initialState();
assert.equal(normalizeDomain(' https://Mon-Cafe.fr/bonjour?secret=oublié#ici '), 'mon-cafe.fr');
assert.equal(normalizeDomain('cafe.example.'), 'cafe.example');
assert.equal(normalizeDomain('café.example'), 'xn--caf-dma.example');
for (const raw of ['', 'pas un domaine', 'localhost', '127.0.0.1', '[::1]', 'site.local', 'https://a.fr:8080', 'https://moi:secret@site.fr', 'mailto:test@site.fr', 'ftp://site.fr', '<script>.fr', '-test.fr', 'a..fr', '__proto__', 'a'.repeat(64) + '.fr', null]) assert.throws(() => normalizeDomain(raw), String(raw));
assert.deepEqual(followDomain(subscriptions, 'collectif.example'), { domain: 'collectif.example', demo: true, added: true });
assert.equal(followDomain(subscriptions, 'https://collectif.example').added, false);
assert.equal(followDomain(subscriptions, 'https://ami.example').demo, false);
assert.equal(followDomain(subscriptions, 'AMI.example').added, false);
assert.deepEqual(subscriptions.addedDomains, ['ami.example']);
assert.equal(visiblePosts(subscriptions).length, 16);
assert.deepEqual(restoreState(JSON.stringify(subscriptions)), subscriptions);
const beforeAddedDomains = initialState(); delete beforeAddedDomains.addedDomains;
assert.deepEqual(restoreState(JSON.stringify(beforeAddedDomains)).addedDomains, []);
for (const invalidDomains of ['oops', ['javascript:alert(1)'], ['cafe.example'], ['ami.example', 'ami.example'], ['AMI.example']]) assert.equal(restoreState(JSON.stringify({ ...subscriptions, addedDomains: invalidDomains })), null);
for (let i = 1; i < 100; i++) followDomain(subscriptions, `ami${i}.example`);
assert.equal(followDomain(subscriptions, 'ami.example').added, false);
assert.throws(() => followDomain(subscriptions, 'de-trop.example'));
assert.ok(restoreState(JSON.stringify(subscriptions)));
console.log('OK : ajout de domaines, normalisation, doublons, entrées dangereuses, limite et compatibilité des essais.');
